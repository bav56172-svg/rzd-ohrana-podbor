//            прошёл Тест 1 (не отсеян и набрал проходной балл).
//
// type: "filter"  — да/нет вопрос, конкретный ответ = мгновенный отсев
// type: "choice"  — закрытый вопрос с баллами за вариант
// type: "info"    — фиксируется в анкете, не отсеивает и не даёт баллов
// type: "rating"  — самооценка по шкале, без баллов
//
// Механический тест на внимание (вопрос 4 старого черновика Блока 2) в v1
// не реализован: таймер с автоскрытием текста через текстовый бот сделать
// неудобно/ненадёжно. Обсудить с Андреем отдельно, если нужен.

export const PASS_THRESHOLD_PERCENT = 60;

function computeMaxScore(questions) {
  return questions
    .filter((q) => q.type === "choice")
    .reduce((sum, q) => sum + Math.max(...q.options.map((o) => o.score ?? 0)), 0);
}

